// Writes the checklist variant's config, video.sjekkliste.json, from video.config.json. Generated – never edit it;
// change video.config.json and run this again (pnpm review:sjekkliste and pnpm final do that for you).
//
//   node extras/variant.mjs [--config video.config.json]      (pnpm variant)
//
// Every clip is made in ONE variant: "variant": "captions" (default) or "checklist" in video.config.json.
// Differences from the main config:
//   output   <name>.mp4 – the file name never says «sjekkliste» (only when both variants are made on explicit
//            request does the checklist file get the -sjekkliste suffix, so the two don't overwrite each other)
//   dirs     clips → clips-sjekkliste, stills → stills-sjekkliste (the variants never overwrite each other's clips)
//   scenes   each scene's file NN-slug.html → NN-slug-sjekkliste.html (or scene.checklistFile when set)
// For a captions clip this script writes nothing. Legacy configs with "variants": [...] are still read.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const ci = args.indexOf("--config");
const src = path.resolve(ci === -1 ? "video.config.json" : args[ci + 1]);
if (!existsSync(src)) throw new Error(`Fant ikke ${src}`);
const raw = JSON.parse(readFileSync(src, "utf8"));
const variants = raw.variant ? [raw.variant] : (raw.variants ?? ["captions"]);
const out = path.join(path.dirname(src), "video.sjekkliste.json");

if (!variants.includes("checklist")) {
  console.log(`Klippet bruker ikke sjekkliste-varianten (${JSON.stringify(variants)}) – skrev ingenting.`);
  process.exit(0);
}

const pad2 = (id) => (/^\d+$/.test(String(id)) ? String(id).padStart(2, "0") : String(id));
const base = (raw.output ?? `${raw.name ?? "video"}.mp4`).replace(/\.mp4$/i, "");
const dirs = { scenes: "scenes", clips: "clips", stills: "stills", audio: "audio", ...(raw.dirs ?? {}) };
const variant = {
  ...raw,
  _doc: `GENERATED by extras/variant.mjs from ${path.basename(src)} – do not edit. Checklist variant.`,
  output: variants.includes("captions") ? `${base}-sjekkliste.mp4` : `${base}.mp4`,
  dirs: { ...dirs, clips: `${dirs.clips}-sjekkliste`, stills: `${dirs.stills}-sjekkliste` },
  scenes: (raw.scenes ?? []).map((s) => {
    const { checklistFile, ...rest } = s;
    const file = checklistFile ?? (s.file ? s.file.replace(/\.html$/i, "-sjekkliste.html") : `${pad2(s.id)}-${s.slug}-sjekkliste.html`);
    return { ...rest, file };
  }),
};
writeFileSync(out, JSON.stringify(variant, null, 2) + "\n");
console.log(`Skrev ${path.relative(process.cwd(), out) || out} (${variant.scenes.length} scener → ${variant.output})`);
